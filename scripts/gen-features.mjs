#!/usr/bin/env node
// SPDX-License-Identifier: GPL-3.0-or-later
//
// The features page and the public docs list come from the feature records, not from hand-typed
// text. One record per feature, content/features/<id>.yml:
//
//   id        lower-kebab, the key of the feature's text in i18n/locales/<lang>/features.json
//   title     the English name; it must equal that file's `features.<id>.title`
//   state     building | measured | live
//   manual    the manual pages of the feature, as docs/manual/<page>.md
//   public    true: listed on the site, and its manual pages are published
//
// The records are the public projection of the console's own feature records; `--sync <checkout>`
// copies them from <checkout>/docs/features/. Two files are generated and committed, like the API
// reference, so the CI run needs no checkout:
//
//   app/data/features.json   the states the features page reads (app/pages/features.vue)
//   deploy/public-docs.txt   deploy/public-docs.base.txt with `#@ feature-pages` replaced by the
//                            manual pages of the public records
//
// Usage:
//   node scripts/gen-features.mjs                 write both files
//   node scripts/gen-features.mjs --verify        fail when a record is invalid or a generated file
//                                                 is stale or was edited by hand
//   node scripts/gen-features.mjs --sync <dir>    copy the records from a checkout, then write

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml } from 'yaml';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const STATES = ['building', 'measured', 'live'];
export const LANGS = ['en', 'ca'];
const KEYS = ['id', 'title', 'state', 'manual', 'public'];
const ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const PAGE = /^docs\/manual\/[a-z0-9][a-z0-9/-]*\.md$/;
export const MARK = '#@ feature-pages';
export const HEADER =
  '# GENERATED by scripts/gen-features.mjs from content/features/*.yml and deploy/public-docs.base.txt.\n' +
  '# Do not edit this file: edit a record or the base list, then run `npm run features:gen`.\n' +
  '# `npm run features:verify` fails on a hand edit or a stale copy.\n';

/** Parse and validate record texts, [{ file, text }]. Returns { records, problems }. */
export function readRecords(files) {
  const records = [];
  const problems = [];
  const ids = new Set();
  for (const { file, text } of files) {
    let r;
    try {
      r = parseYaml(text);
    } catch (e) {
      problems.push(`${file}: not YAML (${e.message.split('\n')[0]})`);
      continue;
    }
    if (r === null || typeof r !== 'object' || Array.isArray(r)) {
      problems.push(`${file}: not a mapping`);
      continue;
    }
    for (const k of Object.keys(r)) if (!KEYS.includes(k)) problems.push(`${file}: unknown key ${k}`);
    for (const k of KEYS) if (!(k in r)) problems.push(`${file}: no ${k}`);
    if (typeof r.id !== 'string' || !ID.test(r.id)) problems.push(`${file}: id must be lower-kebab`);
    else {
      if (file.replace(/^.*\//, '') !== `${r.id}.yml`) problems.push(`${file}: the file must be named ${r.id}.yml`);
      if (ids.has(r.id)) problems.push(`${file}: id ${r.id} is used twice`);
      ids.add(r.id);
    }
    if (typeof r.title !== 'string' || r.title.trim() === '') problems.push(`${file}: no title`);
    if (!STATES.includes(r.state)) problems.push(`${file}: state must be one of ${STATES.join(', ')}`);
    if (typeof r.public !== 'boolean') problems.push(`${file}: public must be true or false`);
    if (!Array.isArray(r.manual) || r.manual.some((m) => typeof m !== 'string' || !PAGE.test(m))) {
      problems.push(`${file}: manual is a list of docs/manual/<page>.md`);
    }
    records.push({ file, ...r });
  }
  const owner = new Map();
  for (const r of records) {
    for (const m of Array.isArray(r.manual) ? r.manual : []) {
      if (owner.has(m)) problems.push(`${r.file}: ${m} is already named by ${owner.get(m)}`);
      else owner.set(m, r.id);
    }
  }
  return { records: records.sort((a, b) => String(a.id).localeCompare(String(b.id))), problems };
}

/** The data the features page reads. */
export function featuresJson(records) {
  const features = records.filter((r) => r.public).map(({ id, title, state }) => ({ id, title, state }));
  return `${JSON.stringify({ generated: 'scripts/gen-features.mjs from content/features; do not edit', features }, null, 2)}\n`;
}

/** The public docs list: the base with the records' pages in place of the marker. */
export function publicDocs(base, records) {
  if (base.split('\n').filter((l) => l.trim() === MARK).length !== 1) throw new Error(`the base list needs exactly one "${MARK}" line`);
  const pages = records
    .filter((r) => r.public)
    .flatMap((r) => r.manual)
    .map((m) => m.replace(/^docs\//, ''))
    .sort();
  const listed = new Set(base.split('\n').map((l) => l.trim()));
  const dup = pages.filter((p) => listed.has(p));
  if (dup.length) throw new Error(`the base list also names ${dup.join(', ')}; a page a record owns is not listed by hand`);
  return HEADER + base.split('\n').flatMap((l) => (l.trim() === MARK ? pages : [l])).join('\n');
}

/** What the features page must show: every public record has a row, and no row lacks a record. */
export function pageProblems(records, pageText, locales) {
  const out = [];
  const used = [...pageText.matchAll(/stateOf\('([a-z0-9-]+)'\)/g)].map((m) => m[1]);
  const pub = records.filter((r) => r.public).map((r) => r.id);
  for (const id of pub) if (!used.includes(id)) out.push(`app/pages/features.vue has no row for the record ${id}`);
  for (const id of used) if (!pub.includes(id)) out.push(`app/pages/features.vue shows ${id}, which has no public record`);
  if (/\bstate\s*=\s*"(?:live|measured|building)"/.test(pageText)) out.push('app/pages/features.vue types a state by hand');
  for (const r of records.filter((x) => x.public)) {
    for (const [lang, j] of Object.entries(locales)) {
      const t = j?.features?.[r.id]?.title;
      if (typeof t !== 'string') out.push(`i18n ${lang}: no features.${r.id}.title`);
      else if (lang === 'en' && t !== r.title) out.push(`i18n en: features.${r.id}.title is "${t}", the record says "${r.title}"`);
    }
  }
  return out;
}

const recordFiles = (dir) =>
  readdirSync(dir)
    .filter((f) => f.endsWith('.yml'))
    .sort()
    .map((f) => ({ file: `content/features/${f}`, text: readFileSync(join(dir, f), 'utf8') }));

function load() {
  const dir = join(root, 'content/features');
  const { records, problems } = readRecords(existsSync(dir) ? recordFiles(dir) : []);
  const base = readFileSync(join(root, 'deploy/public-docs.base.txt'), 'utf8');
  const locales = {};
  for (const l of LANGS) {
    const f = join(root, `i18n/locales/${l}/features.json`);
    if (existsSync(f)) locales[l] = JSON.parse(readFileSync(f, 'utf8'));
  }
  const pageText = readFileSync(join(root, 'app/pages/features.vue'), 'utf8');
  return { records, problems: [...problems, ...pageProblems(records, pageText, locales)], base };
}

function outputs({ records, base }) {
  return {
    'app/data/features.json': featuresJson(records),
    'deploy/public-docs.txt': publicDocs(base, records),
  };
}

function main(argv) {
  const sync = argv.indexOf('--sync');
  if (sync >= 0) {
    const src = resolve(argv[sync + 1] ?? '');
    const from = join(src, 'docs/features');
    if (!existsSync(from)) {
      console.error(`[gen-features] ${from} does not exist; the records are not in that checkout`);
      return 1;
    }
    const { records, problems } = readRecords(recordFiles(from).map((f) => ({ ...f, text: projection(f.text) })));
    if (problems.length) return fail(problems);
    mkdirSync(join(root, 'content/features'), { recursive: true });
    for (const r of records) {
      const { file, ...rest } = r;
      writeFileSync(join(root, 'content/features', `${r.id}.yml`), `# SPDX-License-Identifier: GPL-3.0-or-later\n${yamlOf(rest)}`);
    }
  }
  const state = load();
  if (state.problems.length) return fail(state.problems);
  const out = outputs(state);
  if (argv.includes('--verify')) {
    const stale = Object.entries(out).filter(([f, text]) => !existsSync(join(root, f)) || readFileSync(join(root, f), 'utf8') !== text);
    if (stale.length) {
      return fail(stale.map(([f]) => `${f} is stale or was edited by hand; run npm run features:gen and commit the result`));
    }
    console.log(`[gen-features] ${state.records.length} records; ${Object.keys(out).join(' and ')} match`);
    return 0;
  }
  for (const [f, text] of Object.entries(out)) writeFileSync(join(root, f), text);
  console.log(`[gen-features] ${state.records.length} records -> ${Object.keys(out).join(', ')}`);
  return 0;
}

/** A checkout's record reduced to the public keys, as YAML text. */
function projection(text) {
  const r = parseYaml(text);
  if (r === null || typeof r !== 'object') return text;
  const keep = {};
  for (const k of KEYS) if (k in r) keep[k] = r[k];
  return yamlOf(keep);
}

function yamlOf(r) {
  const lines = [`id: ${r.id}`, `title: ${r.title}`, `state: ${r.state}`];
  lines.push(r.manual.length ? `manual:\n${r.manual.map((m) => `  - ${m}`).join('\n')}` : 'manual: []');
  lines.push(`public: ${r.public}`);
  return `${lines.join('\n')}\n`;
}

function fail(problems) {
  for (const p of problems) console.error(`[gen-features] ${p}`);
  return 1;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
