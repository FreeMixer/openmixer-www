import { test } from 'node:test';
import assert from 'node:assert/strict';
import { stripHtmlComments } from './md-comments.mjs';

test('a comment, on one line or several, leaves the page', () => {
  const md = '<!-- GENERATED by a tool.\n     Do not edit. -->\n\n# Title\n\nText <!-- inline --> here.\n';
  assert.equal(stripHtmlComments(md), '\n# Title\n\nText here.\n');
});

test('a comment inside a fenced code block stays', () => {
  const md = 'Before\n\n```html\n<!-- shown on purpose -->\n```\n\n<!-- gone -->\nAfter\n';
  assert.equal(stripHtmlComments(md), 'Before\n\n```html\n<!-- shown on purpose -->\n```\n\nAfter\n');
});
